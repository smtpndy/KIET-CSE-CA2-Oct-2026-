import pandas as pd

columns = [
    "Pregnancies", "Glucose", "BloodPressure",
    "SkinThickness", "Insulin", "BMI",
    "DiabetesPedigreeFunction", "Age", "Outcome"
]

df = pd.read_csv("pima-indians-diabetes.csv", header=None)
df.columns = columns

print("Dataset shape:", df.shape)
print(df.head())
print(df["Outcome"].value_counts())
print(df.isnull().sum())

from sklearn.model_selection import train_test_split

X = df.drop("Outcome", axis=1)
y = df["Outcome"]

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training samples:", X_train.shape[0])
print("Testing samples:", X_test.shape[0])

from sklearn.ensemble import RandomForestClassifier

model = RandomForestClassifier(
    n_estimators=200,
    max_depth=10,
    min_samples_split=5,
    random_state=42,
    class_weight="balanced"
)

model.fit(X_train, y_train)

print("Model training completed!")

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    roc_auc_score
)

y_pred = model.predict(X_test)
y_prob = model.predict_proba(X_test)[:, 1]

print("Accuracy:", round(accuracy_score(y_test, y_pred), 4))
print("ROC-AUC:", round(roc_auc_score(y_test, y_prob), 4))

print("\nClassification Report:")
print(classification_report(y_test, y_pred))

print("Confusion Matrix:")
print(confusion_matrix(y_test, y_pred))

import joblib

model_artifact = {
    "model": model,
    "feature_names": X.columns.tolist(),
    "model_params": model.get_params(),
    "test_metrics": {
        "accuracy": accuracy_score(y_test, y_pred),
        "roc_auc": roc_auc_score(y_test, y_prob)
    }
}

joblib.dump(model_artifact, "model.joblib")

print("Saved successfully as model.joblib")

import joblib
import pandas as pd

artifact = joblib.load("model.joblib")

loaded_model = artifact["model"]

print("Model parameters:")
print(artifact["model_params"])

print("\nTest metrics:")
print(artifact["test_metrics"])

sample = pd.DataFrame(
    [[1, 85, 66, 29, 0, 26.6, 0.351, 31]],
    columns=artifact["feature_names"]
)

prediction = loaded_model.predict(sample)[0]
probability = loaded_model.predict_proba(sample)[0][1]

print("Predicted outcome:", prediction)
print("Predicted probability of class 1:", round(probability, 4))

